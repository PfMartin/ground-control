import { act, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { App } from './App'
import { ChatController } from './controller'
import { fakeTransports, readyFrame } from './test-helpers'
import { THEME_STORAGE_KEY } from './theme'

describe('chat UI', () => {
  beforeEach(() => localStorage.clear())
  it('defaults to light and persists the keyboard-accessible SSP theme switch', async () => {
    const user = userEvent.setup()
    const controller = new ChatController(localStorage, fakeTransports().factory)
    const view = render(<App controller={controller} />)
    const toggle = screen.getByRole('switch', { name: 'SSP dark theme' })
    expect(toggle).toHaveAttribute('aria-checked', 'false')
    expect(document.documentElement).toHaveAttribute('data-theme', 'light')
    toggle.focus()
    await user.keyboard(' ')
    expect(toggle).toHaveAttribute('aria-checked', 'true')
    expect(document.documentElement).toHaveAttribute('data-theme', 'ssp')
    expect(localStorage.getItem(THEME_STORAGE_KEY)).toBe('ssp')
    view.unmount()
    render(<App controller={controller} />)
    expect(screen.getByRole('switch', { name: 'SSP dark theme' })).toHaveAttribute('aria-checked', 'true')
    await user.click(screen.getByRole('switch', { name: 'SSP dark theme' }))
    expect(document.documentElement).toHaveAttribute('data-theme', 'light')
    expect(localStorage.getItem(THEME_STORAGE_KEY)).toBe('light')
  })
  it('falls back to light for an invalid preference and warns if the choice cannot be saved', async () => {
    localStorage.setItem(THEME_STORAGE_KEY, 'invalid')
    const controller = new ChatController(localStorage, fakeTransports().factory)
    const setItem = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('blocked') })
    try {
      render(<App controller={controller} />)
      expect(document.documentElement).toHaveAttribute('data-theme', 'light')
      await userEvent.click(screen.getByRole('switch', { name: 'SSP dark theme' }))
      expect(document.documentElement).toHaveAttribute('data-theme', 'ssp')
      expect(screen.getByText(/Theme preference could not be saved/)).toBeInTheDocument()
    } finally { setItem.mockRestore() }
  })
  it('still opens in light mode when the theme preference cannot be read', () => {
    const controller = new ChatController(localStorage, fakeTransports().factory)
    const getItem = vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new Error('blocked') })
    try {
      render(<App controller={controller} />)
      expect(document.documentElement).toHaveAttribute('data-theme', 'light')
      expect(screen.getByRole('switch', { name: 'SSP dark theme' })).toHaveAttribute('aria-checked', 'false')
    } finally { getItem.mockRestore() }
  })
  it('offers a keyboard-accessible skip link to the workspace', async () => {
    const user = userEvent.setup()
    render(<App controller={new ChatController(localStorage, fakeTransports().factory)} />)
    await user.tab()
    const skip = screen.getByRole('link', { name: 'Skip to workspace' })
    expect(skip).toHaveFocus()
    expect(skip).toHaveAttribute('href', '#workspace')
    expect(screen.getByRole('main')).toHaveAttribute('id', 'workspace')
  })
  it('connects with a token, waits for readiness, streams Markdown, and labels historical sessions', async () => {
    const user = userEvent.setup(); const fake = fakeTransports(); const controller = new ChatController(localStorage, fake.factory)
    render(<App controller={controller} />)
    const input = screen.getByLabelText('Message (Markdown supported)')
    const send = screen.getByRole('button', { name: 'Send message' })
    expect(send).toBeDisabled()
    await user.click(screen.getByRole('button', { name: /connect/i }))
    await user.type(screen.getByLabelText('Bearer token'), 'secret-token')
    await user.click(within(screen.getByRole('form', { name: 'Backend connection' })).getByRole('button', { name: 'Connect' }))
    expect(send).toBeDisabled()
    act(() => fake.connections[0].handlers.onOpen())
    expect(screen.getByText('Connecting')).toBeInTheDocument()
    act(() => fake.connections[0].handlers.onFrame(readyFrame))
    await user.type(input, '**hello**{Shift>}{Enter}{/Shift}world')
    await user.keyboard('{Enter}')
    expect(send).toBeDisabled()
    expect(screen.getByText('hello').tagName).toBe('STRONG')
    const prompt = fake.connections[0].send.mock.calls[0][0]
    act(() => {
      fake.connections[0].handlers.onFrame({ type: 'response', command: 'prompt', id: prompt.id, success: true, data: { disposition: 'started' } })
      fake.connections[0].handlers.onFrame({ type: 'agent_start' })
      fake.connections[0].handlers.onFrame({ type: 'message_start', message: { role: 'assistant', content: [] } })
      fake.connections[0].handlers.onFrame({ type: 'message_update', assistantMessageEvent: { type: 'text_delta', contentIndex: 0, delta: 'Hello **world**' } })
    })
    expect(screen.getByText('world', { selector: 'strong' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Stop' })).toBeInTheDocument()
    act(() => {
      fake.connections[0].handlers.onFrame({ type: 'message_end', message: { role: 'assistant', content: [{ type: 'text', text: 'Hello **world**\n\n<script>alert(1)</script>\n\n[bad](javascript:alert(1))' }], stopReason: 'stop' } })
      fake.connections[0].handlers.onFrame({ type: 'agent_end' })
      fake.connections[0].handlers.onFrame({ type: 'agent_settled', aborted: false })
    })
    expect(document.querySelector('script')).toBeNull()
    expect(screen.getByText('bad').getAttribute('href') ?? '').not.toMatch(/^javascript:/i)
    await user.click(screen.getByRole('button', { name: 'Disconnect' }))
    expect(screen.getByText(/HISTORICAL SESSION/)).toBeInTheDocument()
    expect(screen.getByText(/Reconnecting creates a fresh session/)).toBeInTheDocument()
  })
  it('handles a startup extension dialog without prematurely enabling input', async () => {
    const fake = fakeTransports(); const controller = new ChatController(localStorage, fake.factory)
    await controller.connect('secret')
    render(<App controller={controller} />)
    act(() => fake.connections[0].handlers.onFrame({ type: 'extension_ui_request', id: 'dialog', method: 'confirm', title: 'Dangerous?', message: 'Continue?' }))
    const dialog = screen.getByRole('dialog', { name: 'Dangerous?' })
    expect(screen.getByRole('button', { name: 'Send message' })).toBeDisabled()
    await userEvent.click(within(dialog).getByRole('button', { name: 'No' }))
    expect(fake.connections[0].send.mock.calls[0][0]).toEqual({ type: 'extension_ui_response', id: 'dialog', confirmed: false })
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    act(() => fake.connections[0].handlers.onFrame(readyFrame))
    expect(controller.getSnapshot().canSend).toBe(true)
    act(() => controller.disconnect())
  })
  it('manages backend endpoints, limits, and confirms destructive edits', async () => {
    const user = userEvent.setup(); vi.spyOn(window, 'confirm').mockReturnValue(true)
    const controller = new ChatController(localStorage, fakeTransports().factory)
    render(<App controller={controller} />)
    await user.click(screen.getByRole('button', { name: 'Add backend' }))
    await user.type(screen.getByLabelText('Name'), 'Remote')
    await user.type(screen.getByLabelText('Server base URL'), 'https://example.test/agent')
    fireEvent.change(screen.getByLabelText('Message limit (bytes)'), { target: { value: '4096' } })
    await user.click(screen.getByRole('button', { name: 'Save' }))
    expect(screen.getByRole('heading', { name: 'Remote' })).toBeInTheDocument()
    expect(controller.getSnapshot().data.backends[1]).toMatchObject({ url: 'https://example.test/agent/', maxMessageBytes: 4096 })
    await user.click(screen.getByRole('button', { name: 'Edit backend' }))
    const url = screen.getByLabelText('Server base URL'); await user.clear(url); await user.type(url, 'https://other.test/')
    await user.click(screen.getByRole('button', { name: 'Save' }))
    expect(window.confirm).toHaveBeenCalledWith(expect.stringContaining('delete its local conversation'))
    await user.click(screen.getByRole('button', { name: 'Remove backend' }))
    expect(screen.getByRole('heading', { name: 'Local example' })).toBeInTheDocument()
  })
})
