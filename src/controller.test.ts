import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { ChatController } from './controller'
import { LEGACY_STORAGE_KEY, STORAGE_KEY } from './storage'
import { fakeTransports, readyFrame } from './test-helpers'
import type { AgentTransport } from './transport'

async function setup() {
  const fake = fakeTransports()
  const controller = new ChatController(localStorage, fake.factory)
  await controller.connect('secret-token')
  const connection = fake.connections[0]
  return { fake, controller, connection }
}
function promptId(connection: ReturnType<typeof fakeTransports>['connections'][number]): string {
  const sent = connection.send.mock.calls.slice().reverse().find(([frame]) => frame.type === 'prompt')?.[0]
  if (!sent) throw new Error('No prompt sent')
  return sent.id
}
const assistantStart = { type: 'message_start', message: { role: 'assistant', content: [] } }

describe('Pi conversation controller', () => {
  beforeEach(() => localStorage.clear())
  afterEach(() => vi.useRealTimers())
  it('waits for readiness and reduces deltas, final blocks, multiple messages, and settlement before response', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onOpen()
    expect(controller.getSnapshot().canSend).toBe(false)
    connection.handlers.onFrame(readyFrame)
    expect(controller.send('**First**')).toBe(true)
    const id = promptId(connection)
    expect(connection.send.mock.calls[0][0]).toEqual({ type: 'prompt', id, message: '**First**' })
    connection.handlers.onFrame({ type: 'agent_start' })
    connection.handlers.onFrame({ type: 'message_start', message: { role: 'user', content: '**First**' } })
    connection.handlers.onFrame({ type: 'message_end', message: { role: 'user', content: '**First**' } })
    connection.handlers.onFrame(assistantStart)
    connection.handlers.onFrame({ type: 'message_update', assistantMessageEvent: { type: 'text_delta', contentIndex: 1, delta: 'partial' } })
    connection.handlers.onFrame({ type: 'message_update', assistantMessageEvent: { type: 'thinking_delta', contentIndex: 0, delta: 'SECRET THINKING' } })
    connection.handlers.onFrame({ type: 'message_update', assistantMessageEvent: { type: 'text_end', contentIndex: 1, content: 'authoritative' } })
    connection.handlers.onFrame({ type: 'message_end', message: { role: 'assistant', content: [{ type: 'thinking', thinking: 'SECRET THINKING' }, { type: 'text', text: 'final answer' }], stopReason: 'stop' } })
    connection.handlers.onFrame({ type: 'tool_execution_start', toolCallId: 't', toolName: 'bash', args: { secret: 'SECRET ARGS' } })
    expect(controller.getSnapshot().tools).toEqual([{ id: 't', name: 'bash', state: 'running' }])
    connection.handlers.onFrame({ type: 'tool_execution_end', toolCallId: 't', toolName: 'bash', isError: false, result: 'SECRET RESULT' })
    connection.handlers.onFrame(assistantStart)
    connection.handlers.onFrame({ type: 'message_end', message: { role: 'assistant', content: [{ type: 'text', text: 'second' }], stopReason: 'stop' } })
    connection.handlers.onFrame({ type: 'agent_end' })
    expect(controller.getSnapshot().canSend).toBe(false)
    connection.handlers.onFrame({ type: 'agent_settled', aborted: false })
    expect(controller.getSnapshot().canSend).toBe(false)
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id, success: true, data: { disposition: 'started' } })
    expect(controller.getSnapshot().canSend).toBe(true)
    const backendId = controller.getSnapshot().data.selectedBackendId!
    const messages = controller.getSnapshot().data.conversations[backendId]
    expect(messages.map((message) => message.content)).toEqual(['**First**', 'final answer', 'second'])
    expect(localStorage.getItem(STORAGE_KEY)).not.toMatch(/SECRET (THINKING|ARGS|RESULT)/)
    expect(controller.send('next')).toBe(true)
    expect(connection.send.mock.calls.at(-1)?.[0]).toMatchObject({ type: 'prompt', message: 'next' })
    expect(connection.send.mock.calls.at(-1)?.[0]).not.toHaveProperty('messages')
    controller.disconnect()
  })
  it('handles transformed user input, provider failure, handled prompts, and independent activity', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('original')
    const id = promptId(connection)
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id, success: true, data: { disposition: 'started' } })
    connection.handlers.onFrame({ type: 'agent_start' })
    connection.handlers.onFrame({ type: 'message_end', message: { role: 'user', content: [{ type: 'text', text: 'expanded input' }] } })
    connection.handlers.onFrame(assistantStart)
    connection.handlers.onFrame({ type: 'message_end', message: { role: 'assistant', content: [{ type: 'text', text: 'partial' }], stopReason: 'error', errorMessage: 'Provider failed' } })
    connection.handlers.onFrame({ type: 'agent_settled', aborted: false })
    const messages = controller.getSnapshot().data.conversations[controller.getSnapshot().data.selectedBackendId!]
    expect(messages[1]).toMatchObject({ role: 'backend', content: 'expanded input' })
    expect(messages[2]).toMatchObject({ status: 'failed', error: 'Provider failed' })
    controller.send('/handled')
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id: promptId(connection), success: true, data: { disposition: 'handled' } })
    expect(controller.getSnapshot().canSend).toBe(true)
    connection.handlers.onFrame({ type: 'agent_start' })
    expect(controller.getSnapshot().canSend).toBe(false)
    controller.stop()
    const abort = connection.send.mock.calls.at(-1)?.[0]
    expect(abort?.type).toBe('abort')
    connection.handlers.onFrame({ type: 'agent_settled', aborted: true })
    connection.handlers.onFrame({ type: 'response', command: 'abort', id: abort?.id, success: true })
    expect(controller.getSnapshot().canSend).toBe(true)
    controller.disconnect()
  })
  it('keeps timeout outcomes unknown, accepts late responses, and does not blame a request for server errors', async () => {
    vi.useFakeTimers()
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('maybe executed')
    const id = promptId(connection)
    connection.handlers.onFrame({ type: 'server_error', code: 'INVALID_COMMAND' })
    expect(controller.getSnapshot().notice).toContain('rejected')
    await vi.advanceTimersByTimeAsync(30_000)
    expect(controller.getSnapshot().notice).toContain('outcome is unknown')
    expect(controller.getSnapshot().canSend).toBe(false)
    expect(controller.getSnapshot().data.conversations[controller.getSnapshot().data.selectedBackendId!][0].status).toBe('unknown')
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id, success: true, data: { disposition: 'handled' } })
    expect(controller.getSnapshot().canSend).toBe(true)
    expect(controller.getSnapshot().data.conversations[controller.getSnapshot().data.selectedBackendId!][0].status).toBe('complete')
    controller.disconnect()
  })
  it('does not clear history until a new session is confirmed and handles cancellation', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('keep')
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id: promptId(connection), success: true, data: { disposition: 'handled' } })
    const id = controller.getSnapshot().data.selectedBackendId!
    controller.newSession()
    let command = connection.send.mock.calls.at(-1)?.[0]
    expect(controller.getSnapshot().data.conversations[id]).toHaveLength(1)
    connection.handlers.onFrame({ type: 'response', command: 'new_session', id: command?.id, success: true, data: { cancelled: true } })
    expect(controller.getSnapshot().data.conversations[id]).toHaveLength(1)
    controller.newSession(); command = connection.send.mock.calls.at(-1)?.[0]
    connection.handlers.onFrame({ type: 'response', command: 'new_session', id: command?.id, success: true, data: { cancelled: false } })
    expect(controller.getSnapshot().data.conversations[id]).toHaveLength(0)
    controller.disconnect()
  })
  it('answers startup dialogs once, validates options, expires queues, and dismisses on close', async () => {
    vi.useFakeTimers()
    const { controller, connection } = await setup()
    connection.handlers.onFrame({ type: 'extension_ui_request', id: 'one', method: 'select', title: 'Choose', options: ['allow', 'deny'] })
    connection.handlers.onFrame({ type: 'extension_ui_request', id: 'two', method: 'input', title: 'Value', timeout: 500 })
    expect(controller.getSnapshot().canSend).toBe(false)
    expect(controller.replyDialog('one', { value: 'other' })).toBe(false)
    expect(controller.replyDialog('one', { value: 'deny' })).toBe(true)
    expect(controller.replyDialog('one', { value: 'allow' })).toBe(false)
    expect(connection.send.mock.calls.at(-1)?.[0]).toEqual({ type: 'extension_ui_response', id: 'one', value: 'deny' })
    await vi.advanceTimersByTimeAsync(500)
    expect(controller.getSnapshot().dialogs).toHaveLength(0)
    expect(controller.replyDialog('two', { value: 'late' })).toBe(false)
    connection.handlers.onFrame({ type: 'extension_ui_request', id: 'three', method: 'confirm' })
    controller.disconnect()
    expect(controller.getSnapshot().dialogs).toHaveLength(0)
  })
  it('migrates v1 safely, requires review of non-root or query endpoints, and does not persist tokens', async () => {
    localStorage.setItem(LEGACY_STORAGE_KEY, JSON.stringify({ version: 1, backends: [{ id: 'a', name: 'Old', url: 'wss://example.test/pi?secret=abc' }], selectedBackendId: 'a', conversations: { a: [{ id: 'm', requestId: 'r', role: 'user', content: 'hello', status: 'pending' }] } }))
    const fake = fakeTransports(); const controller = new ChatController(localStorage, fake.factory)
    expect(controller.getSnapshot().data.backends[0]).toMatchObject({ url: 'https://example.test/pi/', needsReview: true, maxMessageBytes: 131072 })
    expect(controller.getSnapshot().data.conversations.a[0]).toMatchObject({ content: 'hello', status: 'unknown', sessionId: 'legacy-a' })
    expect(localStorage.getItem(LEGACY_STORAGE_KEY)).toBeNull()
    expect(localStorage.getItem(STORAGE_KEY)).not.toContain('secret=abc')
    await controller.connect('private-token')
    expect(fake.connections).toHaveLength(0)
    controller.updateBackend('a', 'Old', 'https://example.test/pi/', 131072)
    await controller.connect('private-token')
    expect(fake.connections).toHaveLength(1)
    expect(localStorage.getItem(STORAGE_KEY)).not.toContain('private-token')
    controller.disconnect()
  })
  it('isolates sessions and ignores stale frames after switching or disconnect', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('unfinished')
    const first = controller.getSnapshot().data.selectedBackendId!
    connection.handlers.onFrame({ type: 'agent_start' }); connection.handlers.onFrame(assistantStart)
    connection.handlers.onFrame({ type: 'message_update', assistantMessageEvent: { type: 'text_delta', contentIndex: 0, delta: 'partial' } })
    controller.addBackend('Second', 'https://example.test')
    expect(connection.close).toHaveBeenCalled()
    connection.handlers.onFrame({ type: 'agent_settled', aborted: false })
    expect(controller.getSnapshot().data.conversations[first].map((m) => m.status)).toEqual(['unknown', 'interrupted', 'interrupted'])
    expect(controller.getSnapshot().data.conversations[first][2]).toMatchObject({ role: 'system', content: expect.stringContaining('before settlement') })
    expect(controller.getSnapshot().currentSessionId).toBeNull()
  })
  it('recovers an unsettled accepted run after a tab reload without replaying it', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('accepted')
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id: promptId(connection), success: true, data: { disposition: 'started' } })
    const id = controller.getSnapshot().data.selectedBackendId!
    const restored = new ChatController(localStorage, fakeTransports().factory)
    expect(restored.getSnapshot().data.conversations[id]).toHaveLength(2)
    expect(restored.getSnapshot().data.conversations[id][1]).toMatchObject({ role: 'system', status: 'interrupted' })
    expect(restored.getSnapshot().data.activeRuns).toEqual({})
    expect(new ChatController(localStorage).getSnapshot().data.conversations[id]).toHaveLength(2)
    controller.disconnect()
  })
  it('does not report interruption after a run settled normally', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('done')
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id: promptId(connection), success: true, data: { disposition: 'started' } })
    connection.handlers.onFrame({ type: 'agent_start' }); connection.handlers.onFrame({ type: 'agent_settled', aborted: false })
    const id = controller.getSnapshot().data.selectedBackendId!
    expect(new ChatController(localStorage).getSnapshot().data.conversations[id]).toHaveLength(1)
    controller.disconnect()
  })
  it('records an interrupted run even when an accepted prompt produced no assistant message', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('accepted')
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id: promptId(connection), success: true, data: { disposition: 'started' } })
    connection.handlers.onClose(1006)
    const messages = controller.getSnapshot().data.conversations[controller.getSnapshot().data.selectedBackendId!]
    expect(messages).toHaveLength(2)
    expect(messages[0].status).toBe('complete')
    expect(messages[1]).toMatchObject({ role: 'system', status: 'interrupted' })
  })
  it('handles queued prompts, retries, and late settlement without enabling new prompts', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('queued')
    const id = promptId(connection)
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id, success: true, data: { disposition: 'queued' } })
    connection.handlers.onFrame({ type: 'agent_start' }); connection.handlers.onFrame({ type: 'agent_end', willRetry: true })
    connection.handlers.onFrame({ type: 'auto_retry_start' })
    expect(controller.getSnapshot().canSend).toBe(false)
    expect(controller.getSnapshot().runLabel).toBe('Retrying…')
    connection.handlers.onFrame({ type: 'agent_start' }); connection.handlers.onFrame({ type: 'agent_settled', aborted: false })
    expect(controller.getSnapshot().canSend).toBe(true)
    controller.disconnect()
  })
  it('preserves new activity across reset, and treats disconnected reset as unknown', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('old')
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id: promptId(connection), success: true, data: { disposition: 'handled' } })
    const backend = controller.getSnapshot().data.selectedBackendId!
    controller.newSession(); const id = connection.send.mock.calls.at(-1)![0].id
    connection.handlers.onFrame({ type: 'message_end', message: { role: 'user', content: 'background input' } })
    connection.handlers.onFrame({ type: 'response', command: 'new_session', id, success: true, data: { cancelled: false } })
    expect(controller.getSnapshot().data.conversations[backend].map((item) => item.content)).toEqual(['background input'])
    expect(controller.getSnapshot().data.conversations[backend][0].sessionId).toMatch(/^unknown-/)
    controller.newSession(); connection.handlers.onClose(1011)
    expect(controller.getSnapshot().notice).toContain('outcomes are unknown')
    expect(controller.getSnapshot().data.conversations[backend]).toHaveLength(1)
  })
  it('replies to input/editor dialogs and rejects mixed or oversized replies', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame({ type: 'extension_ui_request', id: 'input', method: 'input', placeholder: 'Type' })
    expect(controller.replyDialog('input', { value: 'x'.repeat(131073) })).toBe(false)
    expect(controller.replyDialog('input', { value: 'hello' })).toBe(true)
    expect(connection.send.mock.calls.at(-1)?.[0]).toEqual({ type: 'extension_ui_response', id: 'input', value: 'hello' })
    connection.handlers.onFrame({ type: 'extension_ui_request', id: 'editor', method: 'editor', prefill: 'start' })
    expect(controller.replyDialog('editor', { value: 'text', cancelled: true } as { value: string })).toBe(false)
    expect(controller.replyDialog('editor', { cancelled: true })).toBe(true)
    expect(connection.send.mock.calls.at(-1)?.[0]).toEqual({ type: 'extension_ui_response', id: 'editor', cancelled: true })
    connection.handlers.onFrame({ type: 'extension_ui_request', id: 'editor', method: 'editor' })
    expect(controller.getSnapshot().dialogs).toHaveLength(0)
    controller.disconnect()
  })
  it('cancels ticket requests and closes late transports after switching', async () => {
    let resolve!: (value: AgentTransport) => void
    const late = { send: vi.fn<AgentTransport['send']>(), close: vi.fn<AgentTransport['close']>() }
    let signal: AbortSignal | undefined
    const controller = new ChatController(localStorage, async (_url, _token, _limit, _handlers, s) => { signal = s; return new Promise((done) => { resolve = done }) })
    const connecting = controller.connect('secret')
    controller.disconnect()
    expect(signal?.aborted).toBe(true)
    resolve(late); await connecting
    expect(late.close).toHaveBeenCalledOnce()
    expect(controller.getSnapshot().status).toBe('disconnected')
  })
  it.each([1000, 1001, 1003, 1009, 1011, 1013, 1006])('handles close code %i without replaying pending prompts', async (code) => {
    const { controller, connection, fake } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('may have run')
    const backend = controller.getSnapshot().data.selectedBackendId!
    connection.handlers.onClose(code)
    expect(controller.getSnapshot().notice).toContain(String(code))
    expect(controller.getSnapshot().data.conversations[backend][0].status).toBe('unknown')
    await controller.connect()
    expect(fake.connections).toHaveLength(2)
    fake.connections[1].handlers.onFrame(readyFrame)
    expect(fake.connections[1].send).not.toHaveBeenCalled()
    controller.disconnect()
  })
  it('retains failed or timed-out resets, and accepts a late confirmation', async () => {
    vi.useFakeTimers()
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame); controller.send('history')
    connection.handlers.onFrame({ type: 'response', command: 'prompt', id: promptId(connection), success: true, data: { disposition: 'handled' } })
    const backend = controller.getSnapshot().data.selectedBackendId!
    controller.newSession(); let id = connection.send.mock.calls.at(-1)![0].id
    connection.handlers.onFrame({ type: 'response', command: 'new_session', id, success: false, error: 'blocked' })
    expect(controller.getSnapshot().data.conversations[backend]).toHaveLength(1)
    controller.newSession(); id = connection.send.mock.calls.at(-1)![0].id
    await vi.advanceTimersByTimeAsync(30_000)
    expect(controller.getSnapshot().notice).toContain('outcome is unknown')
    expect(controller.getSnapshot().canSend).toBe(false)
    expect(controller.getSnapshot().data.conversations[backend]).toHaveLength(1)
    connection.handlers.onFrame({ type: 'response', command: 'new_session', id, success: true, data: { cancelled: false } })
    expect(controller.getSnapshot().data.conversations[backend]).toHaveLength(0)
    expect(controller.getSnapshot().canSend).toBe(true)
    controller.disconnect()
  })
  it('keeps sending disabled for ready-session dialogs and resumes after cancellation', async () => {
    const { controller, connection } = await setup()
    connection.handlers.onFrame(readyFrame)
    connection.handlers.onFrame({ type: 'extension_ui_request', id: 'editor', method: 'editor' })
    expect(controller.getSnapshot().canSend).toBe(false)
    expect(controller.getSnapshot().canReset).toBe(false)
    controller.replyDialog('editor', { cancelled: true })
    expect(controller.getSnapshot().canSend).toBe(true)
    controller.disconnect()
  })
  it('warns on malformed or unavailable storage and requires explicit confirmation for remote HTTP', async () => {
    localStorage.setItem(STORAGE_KEY, '{bad')
    const controller = new ChatController(localStorage, fakeTransports().factory)
    expect(controller.getSnapshot().storageWarning).toBeTruthy()
    controller.addBackend('Remote', 'http://example.test')
    await controller.connect('secret')
    expect(controller.getSnapshot().notice).toContain('insecure HTTP')
    expect(localStorage.getItem(STORAGE_KEY)).toBe('{bad')
    expect(new ChatController(null).getSnapshot().storageWarning).toBeTruthy()
  })
})
